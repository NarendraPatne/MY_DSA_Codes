import java.util.TreeSet;

public class TreeS {
    public static void main(String[] args) {
        // Tree Set keeps elements in sorted order
        TreeSet<Integer>tset=new TreeSet<>();
        tset.add(4);
        tset.add(1);
        tset.add(3);
        tset.add(8);
        tset.add(10);
        tset.add(9);
        System.out.println(tset);
    }
}
